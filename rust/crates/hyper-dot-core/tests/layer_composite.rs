/// {
///   責務: [grid: テスト用の正の解像度を作る]
///   処理: [
///     1: 幅と高さを検証してResolutionを生成する
///   ]
///   引数: [
///     width: 対象領域の幅
///     height: 対象領域の高さ
///   ]
///   戻り値: [解像度、不正な寸法ならテストを失敗させる]
/// }
fn grid(width: u32, height: u32) -> Resolution {
    Resolution::new(width, height).unwrap()
}

/// {
///   責務: [paint_row: 選択中レイヤーの1行目へ順に色を塗る]
///   処理: [
///     1: 色の並びをx座標0から順に塗る
///   ]
///   引数: [
///     document: 編集する作品
///     colors: 塗るRGBA色の並び
///   ]
///   戻り値: [なし、塗れなければテストを失敗させる]
/// }
fn paint_row(document: &mut LayeredCanvas, colors: &[Color]) {
    for (x, color) in colors.iter().enumerate() {
        document
            .paint(x as u32, 0, *color, DetailPolicy::Preserve)
            .unwrap();
    }
}

/// {
///   責務: [composite_matches_pillow_alpha_composite: 合成結果がPython版のPillow合成と1成分ずつ一致することを回帰検証する]
///   処理: [
///     1: 下層と上層に、Pillowで得た入力の組を1行の画素として塗る
///     2: 合成した各画素を期待結果と比較する
///   ]
///   引数: []
///   戻り値: [なし、不一致ならテストを失敗させる]
/// }
#[test]
fn composite_matches_pillow_alpha_composite() {
    let width = VECTORS.len() as u32;
    let mut document = LayeredCanvas::new(grid(width, 1)).unwrap();
    let below: Vec<Color> = VECTORS.iter().map(|(_, below, _)| *below).collect();
    paint_row(&mut document, &below);
    document.add_layer("上").unwrap();
    let above: Vec<Color> = VECTORS.iter().map(|(above, _, _)| *above).collect();
    paint_row(&mut document, &above);
    let flattened = document.composite().unwrap();
    for (x, (above, below, expected)) in VECTORS.iter().enumerate() {
        assert_eq!(
            flattened.sample(x as u32, 0),
            Ok(*expected),
            "above {above:?} over below {below:?}"
        );
    }
}

/// {
///   責務: [hidden_layers_are_not_composited_and_visibility_is_undoable: 非表示の層が合成されず表示切替をUndoできることを回帰検証する]
///   処理: [
///     1: 2層に不透明な色を塗り、上層を非表示にする
///     2: 合成が下層だけになることと、Undoで戻ることを比較する
///   ]
///   引数: []
///   戻り値: [なし、不一致ならテストを失敗させる]
/// }
#[test]
fn hidden_layers_are_not_composited_and_visibility_is_undoable() {
    let mut document = LayeredCanvas::new(grid(1, 1)).unwrap();
    document
        .paint(0, 0, [10, 20, 30, 255], DetailPolicy::Preserve)
        .unwrap();
    document.add_layer("上").unwrap();
    document
        .paint(0, 0, [200, 0, 0, 255], DetailPolicy::Preserve)
        .unwrap();
    assert_eq!(
        document.composite().unwrap().sample(0, 0),
        Ok([200, 0, 0, 255])
    );
    assert_eq!(document.set_layer_visibility(false, None), Ok(true));
    assert_eq!(document.set_layer_visibility(false, None), Ok(false));
    assert_eq!(
        document.composite().unwrap().sample(0, 0),
        Ok([10, 20, 30, 255])
    );
    assert_eq!(document.undo(), Ok(true));
    assert_eq!(
        document.composite().unwrap().sample(0, 0),
        Ok([200, 0, 0, 255])
    );
}

/// {
///   責務: [refined_layer_doubles_the_output_and_scales_plain_layers: 展開セルがある層だけ出力を2倍にし他層は最近傍拡大されることを回帰検証する]
///   処理: [
///     1: 下層を単色にし、上層の1セルだけを分割して子セルを塗る
///     2: 合成が2倍解像度になり、子セルと拡大された下層の色が正しく重なることを比較する
///   ]
///   引数: []
///   戻り値: [なし、不一致ならテストを失敗させる]
/// }
#[test]
fn refined_layer_doubles_the_output_and_scales_plain_layers() {
    let mut document = LayeredCanvas::new(grid(2, 1)).unwrap();
    document
        .fill(0, 0, [0, 0, 255, 255], DetailPolicy::Preserve)
        .unwrap();
    document.add_layer("上").unwrap();
    assert_eq!(document.native_resolution(), Ok(grid(2, 1)));
    assert_eq!(document.split_cell(1, 0), Ok(true));
    document
        .paint_child(1, 0, (1, 0), [255, 0, 0, 255], DetailPolicy::Preserve)
        .unwrap();
    assert_eq!(document.native_resolution(), Ok(grid(4, 2)));
    let flattened = document.composite().unwrap();
    assert_eq!(flattened.resolution(), grid(4, 2));
    assert_eq!(flattened.sample(0, 1), Ok([0, 0, 255, 255]));
    assert_eq!(flattened.sample(2, 0), Ok([0, 0, 255, 255]));
    assert_eq!(flattened.sample(3, 0), Ok([255, 0, 0, 255]));
}

/// {
///   責務: [render_at_composites_retained_detail_at_the_requested_resolution: 指定解像度の合成が保持細部から直接描画されることを回帰検証する]
///   処理: [
///     1: 2層に半透明の色を塗り、論理解像度を下げて保持する
///     2: 元の解像度で合成した結果が下げる前と同じ画素になることを比較する
///   ]
///   引数: []
///   戻り値: [なし、不一致ならテストを失敗させる]
/// }
#[test]
fn render_at_composites_retained_detail_at_the_requested_resolution() {
    let mut document = LayeredCanvas::new(grid(2, 2)).unwrap();
    document
        .paint(1, 1, [255, 0, 0, 128], DetailPolicy::Preserve)
        .unwrap();
    document.add_layer("上").unwrap();
    document
        .paint(1, 1, [0, 0, 255, 128], DetailPolicy::Preserve)
        .unwrap();
    let before = document.render_at(grid(2, 2)).unwrap();
    assert_eq!(
        document.set_resolution(grid(1, 1), DetailPolicy::Preserve),
        Ok(true)
    );
    assert_eq!(document.render_at(grid(2, 2)).unwrap(), before);
}
